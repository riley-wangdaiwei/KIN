alter table public.canvas_people
  add column if not exists sort_order bigint generated by default as identity;

alter table public.canvas_entries
  add column if not exists sort_order bigint generated by default as identity;

create index if not exists canvas_people_owner_order_idx
  on public.canvas_people (user_id, sort_order);
create index if not exists canvas_entries_owner_order_idx
  on public.canvas_entries (user_id, person_id, sort_order);
